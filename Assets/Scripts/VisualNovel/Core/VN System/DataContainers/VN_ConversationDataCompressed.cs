namespace VISUALNOVEL
{
    /*
     * ============================================================
     * VN_ConversationDataCompressed (Compressed Conversation Save Data)
     * ============================================================
     * 파일(.txt)에 기반한 대화(Conversation)를 세이브 파일에
     * "압축 형태"로 저장하기 위한 데이터 컨테이너.
     *
     * [왜 압축 포맷이 필요한가?]
     * - 대화 파일이 수백 줄에 달할 수 있다.
     * - 매 세이브마다 파일 내용 전체를 저장하면 세이브 파일이 커진다.
     * - 어차피 원본 파일이 프로젝트에 존재하므로,
     *   "어느 파일의 몇 번째 줄부터 몇 번째 줄" 정보만 저장하면 충분하다.
     * - 로드 시 파일을 다시 읽어 해당 범위만 추출하여 복원한다.
     *
     * [VN_ConversationData와의 차이]
     * - 이 클래스: 파일명+인덱스만 저장 → 용량 절약, 원본 파일 필요.
     * - ConversationData: 대화 라인 전체 저장 → 파일 없어도 복원 가능.
     *
     * [직렬화]
     * - VNGameSave.GetConversationData()에서 파일 기반 대화에 이 포맷 사용.
     * - VNGameSave.SetConversationData()에서 역직렬화 후 파일을 다시 읽어 복원.
     * ============================================================
     */
    [System.Serializable]
    public class VN_ConversationDataCompressed
    {
        // ─────────────────────────────────────────────────────────
        // fileName: 원본 대화 파일의 Resources 폴더 기준 경로.
        //   예) "Dialogue/Chapter1/Scene01"
        //   로드 시 Resources.Load<TextAsset>(fileName)으로 파일을 다시 읽는다.
        // ─────────────────────────────────────────────────────────
        public string fileName;

        // ─────────────────────────────────────────────────────────
        // startIndex: 이 대화가 시작되는 파일 내 줄 번호(0-based).
        //   파일 전체를 읽은 후 이 인덱스부터 endIndex까지만 사용한다.
        //   하나의 파일에 여러 대화 구간이 있을 때 구간을 구분하기 위해 필요.
        //
        // endIndex: 이 대화가 끝나는 파일 내 줄 번호(0-based, 포함).
        //   추출할 줄 수 = endIndex - startIndex + 1
        // ─────────────────────────────────────────────────────────
        public int startIndex, endIndex;

        // ─────────────────────────────────────────────────────────
        // progress: 저장 시점에 몇 번째 라인까지 진행되었는지 저장하는 인덱스.
        //   로드 시 이 위치부터 대화를 재개한다.
        //   (startIndex 기준이 아닌, 추출된 lines 리스트 기준의 인덱스)
        // ─────────────────────────────────────────────────────────
        public int progress;
    }
}
